# =========================================================
# IMPORTS
# =========================================================

from langchain_core.tools import tool

# =========================================================
# TOOL CREATION
# =========================================================

@tool
def multiply(a: int, b: int) -> int:
    """
    Multiplies two numbers
    """

    return a * b

# =========================================================
# TOOL EXECUTION
# =========================================================

result = multiply.invoke({

    "a": 3,

    "b": 4
})

print(result)