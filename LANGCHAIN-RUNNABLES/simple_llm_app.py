# =====================================================
# IMPORTS
# =====================================================

from langchain_openai import ChatOpenAI

from dotenv import load_dotenv

# =====================================================
# LOAD ENV VARIABLES
# =====================================================

load_dotenv()

# =====================================================
# CREATE MODEL
# =====================================================

model = ChatOpenAI(

    model='gpt-3.5-turbo',

    temperature=0.7
)

# =====================================================
# USER INPUT
# =====================================================

user_input = input("Enter your question: ")

# =====================================================
# INVOKE MODEL
# =====================================================

result = model.invoke(user_input)

# =====================================================
# OUTPUT
# =====================================================

print("\nAI RESPONSE:\n")

print(result.content)